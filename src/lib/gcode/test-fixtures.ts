/** Spiral/vase-mode motion: Z rises a tiny amount on every single extruding move. */
export function spiralVaseFixture(lines = 60): string {
  const out = ["G21", "G90", "M83"];
  for (let i = 0; i < lines; i++) {
    const z = (0.2 + i * 0.004).toFixed(4);
    out.push(`G1 X${(i % 10).toFixed(1)} Y0 Z${z} E0.1 F1200`);
  }
  out.push("");
  return out.join("\n");
}

