/** Checksummed, numbered lines — all valid. */
export function checksummedLinesFixture(): string {
  const lines = ["G21", "G90 G1 X10 Y10 F1500"];
  const out: string[] = [];
  let n = 0;
  for (const body of lines) {
    const withNumber = `N${n} ${body}`;
    let sum = 0;
    for (const ch of withNumber) sum ^= ch.charCodeAt(0);
    out.push(`${withNumber}*${sum}`);
    n++;
  }
  return out.join("\n") + "\n";
}

