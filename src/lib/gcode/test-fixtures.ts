/** A large file for cancellation testing. */
export function largeCancellationFixture(moves = 5000): string {
  const out = ["G21", "G90", "M83"];
  for (let i = 0; i < moves; i++) out.push(`G1 X${i % 100} Y${(i * 2) % 100} E0.1 F1200`);
  out.push("");
  return out.join("\n");
}
