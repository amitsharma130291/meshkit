/**
 * Deterministic G-code fixtures used only by tests — never imported by
 * app code. Kept small and human-readable except where a stress case
 * genuinely needs to be large.
 */

export function chunkString(text: string, chunkSize: number): Uint8Array[] {
  const bytes = new TextEncoder().encode(text);
  const out: Uint8Array[] = [];
  for (let i = 0; i < bytes.length; i += chunkSize) out.push(bytes.slice(i, i + chunkSize));
  return out;
}

